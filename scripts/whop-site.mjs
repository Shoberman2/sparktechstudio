// Publish this site's build to the Whop website (https://sparktech-studios.whop.site, app app_bAA7EpA5RsPuvO), so the
// Whop copy is the same site as sparktechstudio.com (Spencer, 2026-11-25: "I want the Whop site and the SparkTech site to
// be identical"). Run after `npm run build`:
//   node scripts/whop-site.mjs            package only, into .whop-build/ (no key needed)
//   node scripts/whop-site.mjs --deploy   package, upload, promote and check it live (needs WHOP_API_KEY with
//                                         developer:manage_builds and file uploads)
//
// Whop runs a website as a Cloudflare-style worker plus static files; files that exist are served before the worker runs. The package is the layout Whop's own builds use:
// manifest.json, client/ (every file in dist/) and server/index.js. The worker serves the files the way Vercel does
// (clean URLs, no trailing slash, the redirects in vercel.json, a real 404), and forwards /api/* (the SEO checker) and
// /_vercel/* (Web Analytics) to sparktechstudio.com, so both copies behave the same. Every page's canonical already
// points at sparktechstudio.com, so search engines treat the Whop copy as a duplicate, not a competitor.
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync, cpSync, existsSync } from 'node:fs'
import { resolve, join, relative } from 'node:path'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'

const APP = 'app_bAA7EpA5RsPuvO'
const SITE = 'https://sparktech-studios.whop.site'
const ORIGIN = 'https://www.sparktechstudio.com'
const API = 'https://api.whop.com/api/v1'
const dist = resolve('dist'), out = resolve('.whop-build')
if (!existsSync(join(dist, 'index.html'))) throw new Error('No dist/index.html. Run `npm run build` first.')

let commit = 'local'
try { commit = execFileSync('git', ['rev-parse', '--short', 'HEAD']).toString().trim() } catch { /* not a git checkout */ }
// Unique per package, so the live check can tell two builds of the same commit apart
const sha = `${commit}-${Date.now().toString(36)}`

// vercel.json redirects, as regular expressions the worker can match (":slug" becomes a named group)
const vercel = JSON.parse(readFileSync(resolve('vercel.json'), 'utf8'))
const redirects = (vercel.redirects || []).map(r => ({
  re: '^' + r.source.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/:([a-zA-Z]+)/g, '(?<$1>[^/]+)') + '$',
  dest: r.destination,
  status: r.permanent ? 308 : 307,
}))
const headers = Object.fromEntries(((vercel.headers || []).find(h => h.source === '/(.*)')?.headers || []).map(h => [h.key, h.value]))

// Every page the site has (dist/<route>.html and index.html), so the worker can answer anything else with the real 404.
// Whop's file serving falls back to index.html for unknown paths, so the worker can't ask it whether a page exists.
const pages = readdirSync(dist, { recursive: true }).map(String).filter(f => f.endsWith('.html') && !f.endsWith('/index.html') && f !== '404.html')
const worker = `// Generated by scripts/whop-site.mjs from build ${sha}. Do not edit here.
const ORIGIN = ${JSON.stringify(ORIGIN)}
const REDIRECTS = ${JSON.stringify(redirects)}.map(r => ({ ...r, re: new RegExp(r.re) }))
const HEADERS = ${JSON.stringify({ ...headers, 'x-sparktech-build': sha })}
const PAGES = new Set(${JSON.stringify(pages.map(f => f === 'index.html' ? '/' : '/' + f.replace(/\.html$/, '')))})
const isFile = p => /\\.[a-z0-9]+$/i.test(p)
function finish(res, status = res.status) {
  const out = new Response(res.body, { status, statusText: res.statusText, headers: res.headers })
  for (const [k, v] of Object.entries(HEADERS)) out.headers.set(k, v)
  return out
}
export default {
  async fetch(request, env) {
    const url = new URL(request.url)
    const path = url.pathname
    // Which build is live (files that exist are served by Whop before this worker runs, so this is the check)
    if (path === '/__build') return new Response(${JSON.stringify(sha)}, { headers: { 'content-type': 'text/plain', 'cache-control': 'no-store' } })
    // The SEO checker's API and Web Analytics live on Vercel: forward them so the Whop copy works the same
    if (path.startsWith('/api/') || path.startsWith('/_vercel/')) return fetch(new Request(ORIGIN + path + url.search, request))
    // One address per page, like trailingSlash: false on Vercel
    if (path.length > 1 && path.endsWith('/')) return Response.redirect(url.origin + path.replace(/\\/+$/, '') + url.search, 308)
    for (const r of REDIRECTS) {
      const m = path.match(r.re)
      if (m) return Response.redirect(url.origin + r.dest.replace(/:([a-zA-Z]+)/g, (_, k) => m.groups?.[k] ?? ''), r.status)
    }
    const asset = p => env.ASSETS.fetch(new Request(new URL(p, url.origin), { method: request.method, headers: request.headers }))
    // A page: serve its .html (if Whop answers that with a redirect to the clean address, ask for the clean one)
    const page = async p => { let r = await asset(p === '/' ? '/index.html' : p + '.html'); if (r.status >= 300 && r.status < 400) r = await asset(p); return r }
    if (PAGES.has(path)) return finish(await page(path))
    // Real files are normally served before this worker; anything else here is not a page
    if (isFile(path)) { const r = await asset(path); if (r.ok && !(r.headers.get('content-type') || '').includes('text/html')) return finish(r) }
    return finish(await page('/404'), 404)
  },
}
`

// Package: client/ is dist/ minus the <route>/index.html copies (the worker serves <route>.html for /<route>)
rmSync(out, { recursive: true, force: true })
mkdirSync(join(out, 'client'), { recursive: true })
mkdirSync(join(out, 'server'), { recursive: true })
cpSync(dist, join(out, 'client'), { recursive: true })
const walk = d => readdirSync(d).flatMap(n => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p] })
for (const f of walk(join(out, 'client'))) {
  const rel = relative(join(out, 'client'), f)
  if (rel !== 'index.html' && rel.endsWith('/index.html') && existsSync(join(out, 'client', rel.replace(/\/index\.html$/, '.html')))) rmSync(f)
}
// Note: on the home page (/) Whop swaps in the site title set in its dashboard, plus a script that keeps it there,
// whoever serves the file. Set that title in Whop (Websites, this site's settings) to match the home page's <title>.
writeFileSync(join(out, 'server', 'index.js'), worker)
const client = walk(join(out, 'client')).map(f => relative(join(out, 'client'), f)).sort()
writeFileSync(join(out, 'manifest.json'), JSON.stringify({ version: 1, entry: 'index.js', server: ['index.js'], client }))
const zip = resolve('.whop-build.zip')
rmSync(zip, { force: true })
execFileSync('zip', ['-qr', zip, 'manifest.json', 'server', 'client'], { cwd: out })
const bytes = readFileSync(zip)
const checksum = createHash('sha256').update(bytes).digest('hex')
console.log(`Packaged build ${sha}: ${client.length} files, ${(bytes.length / 1024).toFixed(0)} KB, sha256 ${checksum.slice(0, 12)}`)

if (process.argv.includes('--deploy')) {
  const KEY = (process.env.WHOP_API_KEY || '').replace(/\s+/g, '')
  if (!KEY) throw new Error('Set WHOP_API_KEY to deploy.')
  const H = { Authorization: `Bearer ${KEY}`, 'Api-Version-Date': '2026-11-23-3', Accept: 'application/json', 'Content-Type': 'application/json' }
  const call = async (method, path, body) => {
    const r = await fetch(API + path, { method, headers: H, body: body && JSON.stringify(body) })
    const j = await r.json().catch(() => ({}))
    if (!r.ok) throw new Error(`${method} ${path} -> ${r.status}: ${JSON.stringify(j.error || j).slice(0, 300)}`)
    return j
  }
  const wait = ms => new Promise(r => setTimeout(r, ms))
  // 1. Upload the archive
  const file = await call('POST', '/files', { filename: 'application.zip', byte_size: bytes.length })
  const put = await fetch(file.upload_url, { method: 'PUT', body: bytes, headers: { 'Content-Type': 'application/zip', ...(file.upload_headers || {}) } })
  if (!put.ok) throw new Error(`Upload failed: ${put.status}`)
  let status = file.upload_status
  for (let i = 0; i < 30 && status !== 'ready'; i++) { await wait(1000); status = (await call('GET', `/files/${file.id}`)).upload_status }
  if (status !== 'ready') throw new Error(`Upload never became ready (${status})`)
  // 2. Register the build, wait for Whop to accept it, then make it live
  const build = await call('POST', '/app_builds', { app_id: APP, platform: 'web', attachment: { id: file.id }, checksum })
  let b = build
  for (let i = 0; i < 60 && !['approved', 'rejected', 'failed'].includes(b.status); i++) { await wait(2000); b = await call('GET', `/app_builds/${build.id}`) }
  console.log(`Build ${b.id}: ${b.status}${b.review_message ? ` (${b.review_message})` : ''}`)
  if (b.status !== 'approved' && b.status !== 'draft') throw new Error('Whop did not accept the build. The live site is unchanged.')
  const previous = (await call('GET', `/app_builds?app_id=${APP}&first=10`)).data?.find(x => x.is_production)?.id
  await call('POST', `/app_builds/${b.id}/promote`)
  // 3. Check the live site serves this build; roll back if the home page doesn't come back
  let ok = false
  for (let i = 0; i < 30 && !ok; i++) {
    await wait(3000)
    const live = await fetch(`${SITE}/__build?v=${Date.now()}`).then(r => r.ok ? r.text() : '').catch(() => '')
    const home = live.trim() === sha ? await fetch(`${SITE}/?v=${Date.now()}`).then(r => r.ok ? r.text() : '').catch(() => '') : ''
    ok = home.includes('<div id="root">') && home.includes('sparktechstudio.com')
  }
  if (!ok) {
    if (previous) await call('POST', `/app_builds/${previous}/promote`)
    throw new Error(`${SITE} did not serve build ${sha}. Rolled back to ${previous || 'nothing'}.`)
  }
  console.log(`Live: ${SITE} serves build ${sha} (was ${previous || 'none'})`)
}
